    private void txtsimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txtsimpanActionPerformed
        // TODO add your handling code here:                                         
        String nim = txtnim.getText().trim();
        String nama = txtnama.getText().trim();

        if (nim.isEmpty() || nama.isEmpty()) {
            JOptionPane.showMessageDialog(this, "NIM dan nama wajib diisi!");
            return;
        }

        String prodi = String.valueOf(txtprodi.getSelectedItem());
        String jenisKelamin;

        if (buttonGroupJK.isSelected()) {
            jenisKelamin = "Laki-laki";
        } else if (buttonGroup.isSelected()) {
            jenisKelamin = "Perempuan";
        } else {
            JOptionPane.showMessageDialog(this, "Pilih jenis kelamin!");
            return;
        }

        dataMahasiswa = "NIM: " + nim
                + "\nNama: " + nama
                + "\nProgram Studi: " + prodi
                + "\nJenis Kelamin: " + jenisKelamin;

        JOptionPane.showMessageDialog(this, "Data berhasil disimpan sementara.");

    }//GEN-LAST:event_txtsimpanActionPerformed

    private void txttampilkanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txttampilkanActionPerformed
        // TODO add your handling code here:                                          
        if (dataMahasiswa.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Belum ada data yang disimpan!");
        } else {
            txthasil.setText(dataMahasiswa);
        }

    }//GEN-LAST:event_txttampilkanActionPerformed

    private void txtresetActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txtresetActionPerformed
        // TODO add your handling code here:                                     
        txtnim.setText("");
        txtnama.setText("");
        txtprodi.setSelectedIndex(0);
        buttonGroup1.clearSelection();
        txthasil.setText("");
        dataMahasiswa = "";
        txtnim.requestFocus();
    }//GEN-LAST:event_txtresetActionPerformed

